  // ---- 旧暦変換（lunardate 0.3.0 の LunarDate._from_offset を忠実に再現） ----
  function yearInfoToYearDay(info) {
    var res = 29 * 12;
    var leap = (info % 16 !== 0);
    if (leap) res += 29;
    info = floorDiv(info, 16);
    for (var i = 0; i < 12 + (leap ? 1 : 0); i++) {
      if (info % 2 === 1) res += 1;
      info = floorDiv(info, 2);
    }
    return res;
  }
  var LUNAR_YEAR_DAYS = LUNAR_YEAR_INFOS.map(yearInfoToYearDay);
  var LUNAR_START_ORD = toOrdinal({ year: 1900, month: 1, day: 31 });

  function lunarEnumMonth(info) {
    var months = [];
    for (var i = 1; i <= 12; i++) months.push([i, 0]);
    var leap = info % 16;
    if (leap !== 0 && leap <= 12) months.splice(leap, 0, [leap, 1]);
    return months.map(function (m) {
      var days = m[1] ? ((info >> 16) % 2 + 29) : ((info >> (16 - m[0])) % 2 + 29);
      return [m[0], days, m[1]];
    });
  }
  function lunarFromSolar(dt) {
    var offset = toOrdinal(dt) - LUNAR_START_ORD;
    var idx;
    for (idx = 0; idx < LUNAR_YEAR_DAYS.length; idx++) {
      if (offset < LUNAR_YEAR_DAYS[idx]) break;
      offset -= LUNAR_YEAR_DAYS[idx];
    }
    if (idx === LUNAR_YEAR_DAYS.length) idx = LUNAR_YEAR_DAYS.length - 1;
    var months = lunarEnumMonth(LUNAR_YEAR_INFOS[idx]);
    var m = months[0];
    for (var k = 0; k < months.length; k++) {
      m = months[k];
      if (offset < m[1]) break;
      offset -= m[1];
    }
    return [1900 + idx, m[0], offset + 1];
  }
  // 新暦 -> 旧暦 (年, 月, 日)。変換に失敗した場合は Python 版と同じ約 354 日周期の近似
  function toLunar(dt) {
    try {
      return lunarFromSolar(dt);
    } catch (e) {
      var base = toOrdinal({ year: dt.year, month: 1, day: 1 });
      var offset = mod(toOrdinal(dt) - base + 21, 354);
      var lmonth = Math.min(floorDiv(offset, 30) + 1, 12);
      var lday = mod(offset, 30) + 1;
      return [dt.year, lmonth, lday];
    }
  }


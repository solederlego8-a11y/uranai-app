  function kanjiToKana(text) {
    var result = [];
    var n = SUUHI_KANA_SEQUENCE.length;
    cps(text).forEach(function (ch) {
      var code = ord(ch);
      if (has(SUUHI_KANJI_READING, ch)) {
        result.push(SUUHI_KANJI_READING[ch]);
      } else if (has(SUUHI_HEPBURN, ch)) {
        result.push(ch);
      } else if (code >= 0x30A1 && code <= 0x30F6) {
        result.push(String.fromCodePoint(code - 0x60));
      } else if (code >= 0x4E00 && code <= 0x9FFF) {
        result.push(SUUHI_KANA_SEQUENCE[code % n]);
        result.push(SUUHI_KANA_SEQUENCE[floorDiv(code, 7) % n]);
      } else if (isAlpha(ch)) {
        result.push(ch.toLowerCase());
      }
    });
    return result.join('');
  }
  function kanaToRomaji(kanaStr) {
    var kana = cps(kanaStr);
    var romaji = [];
    var i = 0;
    while (i < kana.length) {
      var two = kana.slice(i, i + 2).join('');
      if (has(SUUHI_HEPBURN, two)) { romaji.push(SUUHI_HEPBURN[two]); i += 2; continue; }
      var one = kana[i];
      if (has(SUUHI_HEPBURN, one)) romaji.push(SUUHI_HEPBURN[one]);
      else if (isAlpha(one)) romaji.push(one.toLowerCase());
      i += 1;
    }
    return romaji.join('');
  }
  function nameToRomaji(text) { return kanaToRomaji(kanjiToKana(text)); }
  function lettersToNumber(romaji) {
    var total = 0;
    cps(romaji).forEach(function (ch) {
      var c = ord(ch);
      if (c >= 97 && c <= 122) total += c - 97 + 1;
    });
    return total;
  }


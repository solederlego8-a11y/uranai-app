  function validate(form, lang, opts) {
    form = form || {};
    opts = opts || {};
    var msg = lang === 'en' ? APP_ERROR_MESSAGES_EN : APP_ERROR_MESSAGES_JA;
    var today = parseDate(opts.today || form.today || todayJst());
    var yearMax = (opts.today || form.today) ? today.year : YEAR_MAX;
    function fail(text) { return { userData: null, error: text }; }

    var lastName = pyStrip(form.last_name || '');
    var firstName = pyStrip(form.first_name || '');
    if (!lastName || !firstName) return fail(msg.name_required);
    if (pyLen(lastName) > 10 || pyLen(firstName) > 10) return fail(msg.name_too_long);

    var birthYear, birthMonth, birthDay;
    try {
      birthYear = pyInt(has(form, 'birth_year') ? form.birth_year : '');
      birthMonth = pyInt(has(form, 'birth_month') ? form.birth_month : '');
      birthDay = pyInt(has(form, 'birth_day') ? form.birth_day : '');
    } catch (e) {
      return fail(msg.birth_date_invalid);
    }

    if (!(YEAR_MIN <= birthYear && birthYear <= yearMax)) {
      return fail(msg.year_out_of_range.replace('%d', String(YEAR_MIN)).replace('%d', String(yearMax)));
    }
    if (!isValidDate(birthYear, birthMonth, birthDay)) return fail(msg.date_does_not_exist);
    if (toOrdinal({ year: birthYear, month: birthMonth, day: birthDay }) > toOrdinal(today)) {
      return fail(msg.future_date);
    }

    var hourRaw = form.birth_hour;
    hourRaw = (hourRaw === undefined || hourRaw === null) ? '' : pyStrip(String(hourRaw));
    var birthHour;
    if (hourRaw === '') {
      birthHour = null;
    } else {
      try {
        birthHour = pyInt(hourRaw);
      } catch (e) {
        return fail(msg.hour_invalid);
      }
      if (!(0 <= birthHour && birthHour <= 23)) return fail(msg.hour_out_of_range);
    }

    var gender = form.gender || 'unknown';
    if (GENDER_VALUES.indexOf(gender) < 0) gender = 'unknown';

    var prefecture = form.prefecture || 'unknown';
    if (VALID_BIRTHPLACES.indexOf(prefecture) < 0) prefecture = 'unknown';

    return {
      userData: {
        last_name: lastName,
        first_name: firstName,
        birth_year: birthYear,
        birth_month: birthMonth,
        birth_day: birthDay,
        birth_hour: birthHour,
        gender: gender,
        prefecture: prefecture,
        today: isoDate(today)
      },
      error: null
    };
  }


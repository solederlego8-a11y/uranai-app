def kanji_to_kana(text: str) -> str:
    """氏名の漢字列をかな読みに変換する（内部テーブル＋決定論的フォールバック）。"""
    result = []
    for ch in text:
        if ch in KANJI_READING:
            result.append(KANJI_READING[ch])
        elif ch in HEPBURN:
            result.append(ch)
        elif "ァ" <= ch <= "ヶ":
            # 片仮名は平仮名へ変換する
            result.append(chr(ord(ch) - 0x60))
        elif 0x4E00 <= ord(ch) <= 0x9FFF:
            # 未登録の漢字はコードポイントから決定論的にかなを割り当てる
            code = ord(ch)
            result.append(KANA_SEQUENCE[code % len(KANA_SEQUENCE)])
            result.append(KANA_SEQUENCE[(code // 7) % len(KANA_SEQUENCE)])
        elif ch.isalpha():
            result.append(ch.lower())
    return "".join(result)


def kana_to_romaji(kana: str) -> str:
    """かな列をヘボン式ローマ字に変換する。"""
    romaji = []
    i = 0
    while i < len(kana):
        two = kana[i:i + 2]
        if two in HEPBURN:
            romaji.append(HEPBURN[two])
            i += 2
            continue
        one = kana[i]
        if one in HEPBURN:
            romaji.append(HEPBURN[one])
        elif one.isalpha():
            romaji.append(one.lower())
        i += 1
    return "".join(romaji)


def name_to_romaji(text: str) -> str:
    """氏名（漢字・かな混在）をヘボン式ローマ字に変換する。"""
    return kana_to_romaji(kanji_to_kana(text))


def letters_to_number(romaji: str) -> int:
    """ローマ字を A=1..Z=26 に変換して合計する。"""
    total = 0
    for ch in romaji:
        if "a" <= ch <= "z":
            total += ord(ch) - ord("a") + 1
    return total



# 総格の五行（数理を 10 で割った剰余で五行に対応させる）
def total_element(total: int) -> str:
    """総格の数理から五行を求める。"""
    mapping = {0: "水", 1: "木", 2: "木", 3: "火", 4: "火",
               5: "土", 6: "土", 7: "金", 8: "金", 9: "水"}
    return mapping[total % 10]


def calculate(user_data: dict) -> dict:
    """姓名判断を実行し、共通スキーマの dict を返す。"""
    last_name = (user_data.get("last_name") or "").strip()
    first_name = (user_data.get("first_name") or "").strip()
    if not last_name:
        last_name = "名"
    if not first_name:
        first_name = "無"

    ls = name_strokes(last_name)
    fs = name_strokes(first_name)
    if not ls:
        ls = [1]
    if not fs:
        fs = [1]

    tenkaku = sum(ls)                       # 天格＝姓の総画数
    chikaku = sum(fs)                       # 地格＝名の総画数
    jinkaku = ls[-1] + fs[0]                # 人格＝姓の最後 + 名の最初
    soukaku = tenkaku + chikaku             # 総格＝天格＋地格
    gaikaku = tenkaku + chikaku - jinkaku   # 外格＝天格＋地格－人格
    if gaikaku < 1:
        gaikaku = 1

    kaku = {
        "天格": tenkaku, "人格": jinkaku, "地格": chikaku,
        "外格": gaikaku, "総格": soukaku,
    }
    fortunes = {k: fortune_of(v) for k, v in kaku.items()}

    # 五格の吉凶ポイントを重み付けして 1〜100 に正規化する
    weights = {"天格": 0.8, "人格": 1.5, "地格": 1.2, "外格": 1.0, "総格": 1.5}
    base = sum(FORTUNE_POINT[fortunes[k]] * weights[k] for k in kaku)
    base = base / sum(weights.values())

    # 今日の日付との呼応（総格と今日の通日数の相性）で日替わりの揺らぎを作る
    yday = user_data["today"].timetuple().tm_yday
    resonance = (soukaku + yday) % 9  # 0〜8
    daily_bonus = [8, 5, 2, -1, -4, -2, 1, 4, 6][resonance]
    score = utils.clamp_score(utils.expand_score(
        base + daily_bonus, utils.daily_seed(user_data, 1)))

    element = total_element(soukaku)
    lucky_color = utils.ELEMENT_COLOR[element]
    lucky_item = utils.pick(ITEM_BY_JINKAKU, jinkaku)
    lucky_dir = utils.pick(DIR_BY_GAIKAKU, gaikaku)

    summary = "総格%d画「%s」。人格%d画が今日の対人運を導きます。" % (
        soukaku, fortunes["総格"], jinkaku)
    if len(summary) > 50:
        summary = summary[:49] + "。"

    detail = (
        "あなたの姓名は天格%d画（%s）、人格%d画（%s）、地格%d画（%s）、外格%d画（%s）、"
        "総格%d画（%s）で構成されています。中心となる人格は「%s」を示し、"
        "対人関係の場面であなたの持ち味が最もよく現れます。地格は幼少期から培われた素質、"
        "外格は他人から見えるあなたの印象、総格は人生全体の総決算を表します。"
        "本日は総格%d画と今日の暦（通日%d日目）の呼応が%d番目の位相にあり、"
        "%sという流れになります。名前が持つ%sの五行は%s色と響き合いますので、"
        "身に着けるもの・持ち歩くものにその色を一点加えると、名前本来の力が発揮されやすくなります。"
    ) % (
        tenkaku, fortunes["天格"], jinkaku, fortunes["人格"],
        chikaku, fortunes["地格"], gaikaku, fortunes["外格"],
        soukaku, fortunes["総格"], meaning_of(jinkaku),
        soukaku, yday, resonance + 1,
        "名前の力が素直に外へ出ていく" if daily_bonus >= 0 else "名前の力を内側に溜めておくべき",
        element, lucky_color,
    )

    keywords = [meaning_of(jinkaku).split("。")[0], element + "の気",
                "総格" + fortunes["総格"], "人格%d画" % jinkaku]

    return {
        "name": MODULE_NAME,
        "summary": summary,
        "detail": detail,
        "lucky_color": lucky_color,
        "lucky_item": lucky_item,
        "lucky_dir": lucky_dir,
        "score": score,
        "keywords": keywords,
        "raw": {
            "kaku": kaku,
            "fortunes": fortunes,
            "element": element,
            "full_name": last_name + first_name,
            "stroke_detail": {
                "last_name": dict(zip(list(last_name), ls)),
                "first_name": dict(zip(list(first_name), fs)),
            },
        },
    }

def _build_stroke_dict() -> dict:
    """画数グループから 1 文字 -> 画数 の辞書を構築する。"""
    table = {}
    for stroke, chars in STROKE_GROUPS.items():
        for ch in chars:
            # ASCII 混入（データ内の英字）は無視する
            if ord(ch) < 0x3000:
                continue
            table.setdefault(ch, stroke)
    table.update(KANA_STROKES)
    table.update(NUMERAL_STROKES)
    return table


STROKE_DICT = _build_stroke_dict()


def stroke_count(ch: str) -> int:
    """1 文字の画数を返す。辞書にない字は Unicode から近似推定する。"""
    if ch in STROKE_DICT:
        return STROKE_DICT[ch]
    code = ord(ch)
    if 0x4E00 <= code <= 0x9FFF:
        # CJK 統合漢字は康煕部首の配列順とおおむね画数が相関するため、
        # コードポイントを 17 で割った剰余を近似画数として用いる
        return (code - 0x4E00) % 17 + 3
    if 0x3040 <= code <= 0x30FF:
        return code % 4 + 1
    return code % 9 + 1


def name_strokes(text: str) -> list:
    """文字列を 1 文字ずつ画数のリストに変換する。"""
    return [stroke_count(ch) for ch in text if not ch.isspace()]



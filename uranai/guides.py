# slug -> 記事 の索引
GUIDE_BY_SLUG = {g["slug"]: g for g in GUIDES}


def get_guide(slug: str):
    """slug から記事を取得する。存在しない場合は None。"""
    return GUIDE_BY_SLUG.get(slug)


def char_count(guide: dict) -> int:
    """記事の本文文字数をおおまかに数える（一覧の目安表示用）。"""
    total = len(guide.get("lead", ""))
    for section in guide.get("sections", []):
        total += len(section.get("heading", ""))
        for paragraph in section.get("paragraphs", []):
            total += len(paragraph)
    return total

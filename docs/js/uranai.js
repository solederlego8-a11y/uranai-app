  function aggregate(allResults, ud) {
    var results = allResults.map(function (r) {
      return normalizeResult(r, isPlainObject(r) ? (has(r, 'name') ? r.name : '占術') : '占術');
    });

    var weightSum = 0.0, weighted = 0.0;
    results.forEach(function (r) {
      var w = has(AGG_MODULE_WEIGHTS, r.name) ? AGG_MODULE_WEIGHTS[r.name] : DEFAULT_WEIGHT;
      weighted += w * r.score;
      weightSum += w;
    });
    var totalScore = clampScore(weightSum ? weighted / weightSum : 50);

    var rank = scoreRank(totalScore);

    var luckyColor = majorityVote(results, 'lucky_color');
    var luckyItem = majorityVote(results, 'lucky_item');
    var luckyDir = majorityVote(results, 'lucky_dir');

    var luckyNumber = null;
    for (var i = 0; i < results.length; i++) {
      if (results[i].name === '数秘術') {
        var value = (results[i].raw || {}).personal_day_number;
        if (typeof value === 'number' && Number.isInteger(value)) luckyNumber = value;
        break;
      }
    }
    if (luckyNumber === null) {
      luckyNumber = reduceNumber(totalScore + ud.today.month + ud.today.day);
    }

    var todayKeywords = mergeKeywords(results, 5);
    var catScores = categoryScores(results);

    var patternCount = AGG_MESSAGE_TEMPLATES[rank].length;
    var messageKey = mod(yday(ud.today) + totalScore + ud.birth_year + ud.birth_month + ud.birth_day, patternCount);

    var kwPadded = todayKeywords.concat(['今日の巡り', '落ち着き', '丁寧さ']);
    var context = {
      kw1: kwPadded[0], kw2: kwPadded[1], kw3: kwPadded[2],
      color: luckyColor, item: luckyItem, dir: luckyDir,
      number: luckyNumber, score: totalScore, rank: rank
    };
    var overallMessage = buildMessage(rank, messageKey, context);

    var breakdown = {};
    results.forEach(function (r) { breakdown[r.name] = r.score; });

    return {
      total_score: totalScore,
      score_rank: rank,
      lucky_color: luckyColor,
      lucky_color_hex: colorHex(luckyColor),
      lucky_item: luckyItem,
      lucky_dir: luckyDir,
      lucky_number: luckyNumber,
      today_keywords: todayKeywords,
      category_scores: catScores,
      overall_message: overallMessage,
      score_breakdown: breakdown,
      detail_results: results
    };
  }


  function majorityVote(results, key) {
    var keys = [], counts = {};
    results.forEach(function (r) {
      var value = r[key];
      if (!value) return;
      if (!has(counts, value)) { counts[value] = 0; keys.push(value); }
      counts[value] += 1;
    });
    if (!keys.length) return '白';
    var maxCount = Math.max.apply(null, keys.map(function (k) { return counts[k]; }));
    var candidates = keys.filter(function (k) { return counts[k] === maxCount; });
    if (candidates.length === 1) return candidates[0];

    var byModule = {};
    results.forEach(function (r) { byModule[r.name] = r[key]; });
    var priority = AGG_PRIORITY[key] || [];
    for (var i = 0; i < priority.length; i++) {
      var value = byModule[priority[i]];
      if (candidates.indexOf(value) >= 0) return value;
    }
    return candidates.slice().sort(cmpCodePoint)[0];
  }

  function mergeKeywords(results, limit) {
    var counts = {}, order = {}, keys = [];
    results.forEach(function (r) {
      (r.keywords || []).forEach(function (kw) {
        kw = pyStrip(String(kw));
        if (!kw) return;
        if (!has(counts, kw)) { counts[kw] = 0; order[kw] = keys.length; keys.push(kw); }
        counts[kw] += 1;
      });
    });
    var ranked = keys.slice().sort(function (a, b) {
      if (counts[a] !== counts[b]) return counts[b] - counts[a];
      return order[a] - order[b];
    });
    return ranked.slice(0, limit);
  }


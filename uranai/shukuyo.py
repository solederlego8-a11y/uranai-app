def shuku_index(target) -> int:
    """指定日の宿インデックスを返す（旧暦1月1日＝昴宿を基準）。"""
    _, lunar_month, lunar_day = utils.to_lunar(target)
    return (lunar_month * 30 + lunar_day) % 27


def relation_of(natal: int, transit: int) -> str:
    """本命宿と今日の宿の関係名を返す。"""
    diff = (transit - natal) % 27
    if diff == 0:
        return "命"
    return RELATION_CYCLE[(diff - 1) % 9]


def calculate(user_data: dict) -> dict:
    """宿曜占星術を実行し、共通スキーマの dict を返す。"""
    today = user_data["today"]
    natal = shuku_index(utils.birth_date(user_data))
    transit = shuku_index(today)
    relation = relation_of(natal, transit)

    base = RELATION_SCORE[relation]
    score = utils.clamp_score(utils.expand_score(
        base, utils.daily_seed(user_data, 9)))

    lucky_color = SHUKU_COLOR[natal]
    lucky_item = SHUKU_ITEM[natal]
    lucky_dir = SHUKU_DIR[natal]

    lunar = utils.to_lunar(utils.birth_date(user_data))

    summary = "本命宿は%s。今日は「%s」の関係の日です。" % (SHUKU[natal], relation)

    detail = (
        "あなたの生年月日を旧暦に直すと%d年%d月%d日となり、本命宿は%sに定まります。"
        "%sは%s"
        "宿曜経では、本命宿と今日の宿との距離によって一日の質が決まると考えます。"
        "本日の宿は%sで、あなたの本命宿から数えて%d番目にあたり、関係は「%s」です。"
        "%s。"
        "%s"
        "宿曜の実践では、この関係を知ったうえで一日の予定の「重さ」を調整することが要点になります。"
        "本日は%s色を身に着け、%sの方角に意識を向けると、本命宿の加護が働きやすくなります。"
    ) % (
        lunar[0], lunar[1], lunar[2], SHUKU[natal],
        SHUKU[natal], SHUKU_NATURE[SHUKU[natal]] + "。",
        SHUKU[transit], (transit - natal) % 27, relation,
        RELATION_MEANING[relation],
        "重要な予定はこの日に寄せてよいでしょう。" if base >= 74
        else "重要な予定はできるだけ別の日に動かすことをおすすめします。",
        lucky_color, lucky_dir,
    )

    keywords = [SHUKU[natal], relation + "の日", SHUKU[transit] + "巡り",
                RELATION_MEANING[relation].split("。")[0]]

    return {
        "name": MODULE_NAME,
        "summary": summary[:50],
        "detail": detail,
        "lucky_color": lucky_color,
        "lucky_item": lucky_item,
        "lucky_dir": lucky_dir,
        "score": score,
        "keywords": keywords,
        "raw": {
            "natal_shuku": SHUKU[natal],
            "today_shuku": SHUKU[transit],
            "relation": relation,
            "lunar_birth": "%d年%d月%d日" % lunar,
        },
    }
